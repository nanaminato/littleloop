export function translate(value: string, en: boolean) { return en ? english[value] ?? value : value; }

export function apiMessage(raw: string, status: number, en: boolean) {
  if (status === 401) return translate('请检查账号和密码，或重新登录。', en);
  try {
    const parsed = JSON.parse(raw);
    if (parsed && typeof parsed.code === 'string' && serverZh[parsed.code])
      return (en ? serverEn : serverZh)[parsed.code];
    if (typeof parsed === 'string' && !en) return parsed;
  } catch { if (!en && raw && !raw.startsWith('<')) return raw; }
  return translate('请求失败', en) + ' (' + status + ')';
}
