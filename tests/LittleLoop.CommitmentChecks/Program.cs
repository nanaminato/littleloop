using LittleLoop.Core;
using System.Text.Json;

var checks = 0;
void Check(bool value, string name) { if (!value) throw new Exception(name); checks++; Console.WriteLine($"PASS {name}"); }
void Throws(Action action, string name) { try { action(); } catch (InvalidOperationException) { Check(true, name); return; } throw new Exception(name); }
WorkInterpretation Interpret(string text, WorkReference[]? refs = null, string? reply = null, int? version = null) =>
    WorkConversationPolicy.Interpret(new("message", text, reply, ExpectedVersion: version), refs ?? []);
var first = new WorkReference("a", 1, "synthetic", "running", ["origin"]);
Check(Interpret("帮我整理说明").Intent == WorkIntent.Accept, "Chinese acceptance");
Check(Interpret("please help me outline notes").Intent == WorkIntent.Accept, "English acceptance");
Check(Interpret("如果取消任务会怎样").Intent == WorkIntent.None, "hypothetical not command");
Check(Interpret("取消任务？", [first]).Intent == WorkIntent.None, "question not cancellation");
Check(Interpret("“取消任务”", [first]).Intent == WorkIntent.None, "quoted instruction not command");
Check(Interpret("暂停", [first]).Intent == WorkIntent.Pause, "single current target");
Check(Interpret("取消", [first, first with { Id = "b", MessageIds = ["other"] }]).Intent == WorkIntent.Clarify, "ambiguous targets");
Check(Interpret("取消", [first, first with { Id = "b", MessageIds = ["other"] }], "origin").TaskId == "a", "reply anchor");
Check(Interpret("取消", [first], "origin", 0).Intent == WorkIntent.Clarify, "stale target version");
Check(Interpret("继续", [first with { Status = "completed" }], "origin").Intent == WorkIntent.Clarify, "historical evidence not renewed authority");
Check(Interpret("帮我按昨天的继续").Intent == WorkIntent.Clarify, "historical reference asks clarification");
Check(Interpret("stop", Enumerable.Repeat(first, 65).ToArray()).Intent == WorkIntent.Clarify, "reference bound");
var context = WorkConversationPolicy.SelectContext([new("x", "private unrelated", "b"), new("origin", "123456789", "a"), new("y", "abcdef", "a")], "origin", "a", 2, 10);
Check(context.Length == 2 && context[0].Id == "origin" && context.Sum(x => x.Text.Length) == 10, "bounded relevant evidence");
Check(!context.Any(x => x.Id == "x"), "unrelated history excluded");
var s = WorkCommitmentLedger.Apply(WorkCommitmentState.Empty, new("m1", "帮我整理说明"), "a").State;
Check(s.Tasks.Single().Status == "queued", "accept is not dispatch");
s = WorkCommitmentLedger.Dispatch(s, "a", 1, "e1");
Check(WorkCommitmentLedger.CanApprove(s, "a", 1, "e1"), "current approval fence");
var replacement = WorkCommitmentLedger.Apply(s, new("m2", "改为整理摘要"), "b");
s = replacement.State;
Check(s.Tasks.Single(t => t.Id == "a").ExecutionId == "e1", "replacement retains outstanding execution");
Check(!WorkCommitmentLedger.CanApprove(s, "a", 1, "e1"), "late approval rejected");
Throws(() => WorkCommitmentLedger.Dispatch(s, "b", 1, "e2"), "replacement waits for old receipt");
Check(WorkCommitmentLedger.Apply(s, new("m2", "改为整理摘要"), "c").Duplicate, "duplicate replacement no new work");
s = WorkCommitmentLedger.Receive(s, "a", 1, "e1", "completed");
Check(s.Receipts.Single().Late && s.Tasks.Single(t => t.Id == "a").Status == "replaced", "late completion archived without resurrection");
s = WorkCommitmentLedger.Dispatch(s, "b", 1, "e2");
s = WorkCommitmentLedger.Receive(s, "b", 1, "e2", "unknown");
Throws(() => WorkCommitmentLedger.Dispatch(s, "b", 1, "e3"), "unknown result blocks dispatch");
s = WorkCommitmentLedger.Receive(s, "b", 1, "e2", "completed");
Check(s.Tasks.Single(t => t.Id == "b").Status == "completed", "unknown explicitly reconciled");
var restored = JsonSerializer.Deserialize<WorkCommitmentState>(JsonSerializer.Serialize(s))!;
Check(restored.Tasks.Length == 2 && restored.Receipts.Length == 2, "snapshot serialization");
var stale = new WorkInterpretation(WorkIntent.Cancel, "a", 1, null, ["m3"], "stale");
Check(WorkCommitmentLedger.Apply(s, "m3", stale, "unused").State.Tasks[0].Version == 2, "apply checks version again");
// Real cancellation acknowledgment here belongs only to this cooperative, no-side-effect synthetic worker.
var workerState = WorkCommitmentLedger.Apply(WorkCommitmentState.Empty, new("s1", "help me test cancellation"), "s").State;
workerState = WorkCommitmentLedger.Dispatch(workerState, "s", 1, "synthetic");
using var cancellation = new CancellationTokenSource();
var started = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
var worker = Task.Run(async () => { started.SetResult(); try { await Task.Delay(Timeout.Infinite, cancellation.Token); return "completed"; } catch (OperationCanceledException) { return "stopped"; } });
await started.Task;
workerState = WorkCommitmentLedger.Apply(workerState, new("s2", "取消"), "unused").State;
cancellation.Cancel();
Check(workerState.Tasks[0].ExecutionId is not null, "cancel request alone is not stopped");
workerState = WorkCommitmentLedger.Receive(workerState, "s", 1, "synthetic", await worker.WaitAsync(TimeSpan.FromSeconds(5)));
Check(workerState.Tasks[0].Status == "cancelled" && workerState.Tasks[0].ExecutionId is null, "cooperative worker acknowledged cancellation");
var paused = WorkCommitmentLedger.Apply(WorkCommitmentState.Empty, new("p1", "help me make notes"), "p").State;
paused = WorkCommitmentLedger.Apply(paused, new("p2", "pause"), "unused").State;
Check(paused.Tasks[0].Status == "paused", "pause before dispatch");
paused = WorkCommitmentLedger.Apply(paused, new("p3", "resume"), "unused").State;
Check(paused.Tasks[0].Status == "queued" && paused.Tasks[0].Version == 3, "resume increments version");
paused = WorkCommitmentLedger.Apply(paused, new("p4", "revise to write an outline"), "unused").State;
Check(paused.Tasks[0].Goal == "write an outline" && paused.Tasks[0].Version == 4, "full goal revision");
Check(Interpret("补充：保留所有限制", [first]).Intent == WorkIntent.Clarify, "partial amendment not silently destructive");
var saturated = WorkCommitmentState.Empty with { Tasks = Enumerable.Range(0,64).Select(i => new WorkCommitment(i.ToString(), 1, "old", "completed", [])).ToArray() };
Throws(() => WorkCommitmentLedger.Apply(saturated, new("over", "help me more work"), "new"), "bounded task capacity");
var fullJournal = WorkCommitmentState.Empty with { Events = Enumerable.Range(0, WorkCommitmentLedger.MaximumEvents).Select(i => new WorkCommitmentEvent(i.ToString(), stale, null, "old")).ToArray() };
Throws(() => WorkCommitmentLedger.Apply(fullJournal, new("new", "help me more work"), "new"), "bounded journal capacity");
Check(WorkCommitmentLedger.Apply(fullJournal, new("0", "help me more work"), "new").Duplicate, "dedupe retained at journal capacity");
Check(Interpret("cancel", [first], "foreign-room-message").Intent == WorkIntent.Clarify, "foreign anchor not resolved");
Check(WorkCommitmentLedger.Receive(s, "b", 1, "e2", "completed").Receipts.Length == s.Receipts.Length, "receipt dedupe");
Console.WriteLine($"{checks} commitment checks passed.");
